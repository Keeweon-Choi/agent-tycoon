// K7a: regenerates server/src/cld/spec/languageTable.generated.ts from two MIT open-source data files:
//   GitHub Linguist lib/linguist/languages.yml  (what is code / data / prose / markup, per extension)
//   tokei languages.json                          (extensions and comment syntax of 300+ languages)
// usage: node scripts/generate-languages.mjs <languages.yml> <tokei languages.json> <linguist sha> <tokei sha>
import * as fs from 'fs';

const [yml, tokeiFile, linguistSha, tokeiSha] = process.argv.slice(2);
if (!tokeiSha) throw new Error('usage: generate-languages.mjs <languages.yml> <tokei.json> <linguist sha> <tokei sha>');

// Linguist: extension → type. Only the top-level keys, `type:` and the `extensions:` list are read (no yaml library).
const typeOf = new Map(); // ext → Set of types
let type = '';
let inExt = false;
for (const line of fs.readFileSync(yml, 'utf-8').split('\n')) {
  if (/^\S.*:$/.test(line) && !line.startsWith('#') && line !== '---') (type = ''), (inExt = false);
  const t = /^ {2}type: (\w+)/.exec(line);
  if (t) type = t[1];
  const e = inExt && /^ {2}- "?\.([^"\s]+)"?/.exec(line);
  if (/^ {2}extensions:/.test(line)) inExt = true;
  else if (!e && /^ {2}\S/.test(line)) inExt = false;
  if (e) (typeOf.get(e[1].toLowerCase()) ?? typeOf.set(e[1].toLowerCase(), new Set()).get(e[1].toLowerCase())).add(type);
}
// code: tokei knows its comment syntax (Markdown, JSON and the like have none) and Linguist, if it knows the extension, types some language with it as programming.
const isCode = (ext) => !typeOf.has(ext) || typeOf.get(ext).has('programming');

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\\/]/g, '\\$&');
const tokei = JSON.parse(fs.readFileSync(tokeiFile, 'utf-8')).languages;
const code = [];
const seen = new Set();
for (const [key, l] of Object.entries(tokei)) {
  const starts = [...(l.line_comment ?? []), ...(l.multi_line_comments ?? []).map((m) => m[0])];
  // `*` continues a /* … */ comment
  const src = [...new Set([...starts.map(esc), ...(starts.includes('/*') ? ['\\*'] : [])])].join('|');
  const exts = src ? (l.extensions ?? []).map((e) => e.toLowerCase()).filter((e) => !seen.has(e) && isCode(e)) : [];
  if (!exts.length) continue;
  exts.forEach((e) => seen.add(e));
  code.push([l.name ?? key, exts.join(' '), src]);
}
const list = (kind) => [...typeOf].filter(([e, s]) => s.has(kind) && !seen.has(e)).map(([e]) => e).sort().join(' ');
fs.writeFileSync(
  new URL('../server/src/cld/spec/languageTable.generated.ts', import.meta.url),
  `/**
 * GENERATED by scripts/generate-languages.mjs: do not edit. Sources (both MIT):
 *   GitHub Linguist, lib/linguist/languages.yml @ ${linguistSha} (Copyright (c) 2017 GitHub, Inc.)
 *   tokei, languages.json @ ${tokeiSha} (Copyright (c) 2016 Erin Power)
 */

/** [name, extensions (space separated), comment starts (regex source)] of every code language, tokei's order; an extension is in its first language only. */
export const CODE_LANGUAGES: ReadonlyArray<readonly [string, string, string]> = ${JSON.stringify(code, null, 0).replace(/\],\[/g, '],\n  [').replace(/^\[\[/, '[\n  [').replace(/\]\]$/, '],\n]')};

/** Extensions Linguist types as data (settings, tables) or prose (documents) only. */
export const DATA_EXT = ${JSON.stringify(list('data'))};
export const PROSE_EXT = ${JSON.stringify(list('prose'))};
`,
);
console.log(`code languages ${code.length}, extensions ${seen.size}`);
